SEND_LEVELS = {"REVERB": 0.45, "DELAY": 0.35}   # 0.8 is FL's default (0 dB) send level
ARM_TRACK = "VOX MAIN"

MAX_SLOTS = 10
MASTER_NAME = "MASTER"
