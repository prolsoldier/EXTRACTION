def rgb_to_fl(r, g, b):
    return (b << 16) | (g << 8) | r


def index_of(name):
    for offset, (layout_name, _, _) in enumerate(LAYOUT):
        if layout_name == name:
            return FIRST_INSERT + offset
    raise KeyError(name)


def blocked_inserts():
    """Inserts in the layout range that carry a name the user chose (not a default, not one of ours)."""
    ours = {name for name, _, _ in LAYOUT}
