def OnInit():
    _pending.clear()
    _reported.clear()
    _log("ready (build %s). Parts on: %s" % (BUILD, ", ".join(n for n in SECTION_ORDER if n in _modules) or "none"))
    for line in describe():
        _log("  " + line)
    if CONFIRM_SECONDS:
        _log("  keys that change your project need a second press within %g s" % CONFIRM_SECONDS)
    for line in find_conflicts():
        _log("WARNING: " + line + " - change one in CONFIG so they do not fight")
    _call("OnInit")


def OnDeInit():
    _call("OnDeInit")


def OnIdle():
    _call("OnIdle")


def OnNoteOn(event):
    if _guard(event):
        return
    _call("OnNoteOn", event)


def OnNoteOff(event):
    _call("OnNoteOff", event)
    if not event.handled and event.data1 in _command_notes():
        event.handled = True    # the release of a command key should not reach the channel rack either


def OnControlChange(event):
    _call("OnControlChange", event)
